// Use Snowknife's existing .editorconfig and the formatter bundled with the repo's selected .NET SDK.
// Folder mode needs no restore or build and never follows project references into SSX-Library or Unity.
import { spawnSync } from 'node:child_process';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const args = process.argv.slice(2);
if (args.some(arg => arg !== '--check')) {
  console.error('Usage: node tools/format-snowknife.mjs [--check]');
  process.exit(1);
}

const check = args.includes('--check');
let exitCode = 0;
for (const project of ['Snowknife', 'Snowknife.Tests']) {
  const folder = join(root, 'Snowknife', project);
  console.log(`${check ? 'Checking' : 'Formatting'} Snowknife/${project} C# sources`);
  const result = spawnSync('dotnet', [
    'format', 'whitespace', folder, '--folder',
    '--exclude', join(folder, 'bin'), join(folder, 'obj'),
    ...(check ? ['--verify-no-changes'] : []),
  ], {
    cwd: root,
    stdio: 'inherit',
    windowsHide: true,
  });
  // dotnet format skips <auto-generated> sources by default, including ExternalSoundCatalog.Generated.cs.
  if (result.error) {
    console.error(`Snowknife formatter failed: ${result.error.message}`);
    process.exit(1);
  }
  if (result.status !== 0) exitCode = result.status ?? 1;
}
process.exit(exitCode);
