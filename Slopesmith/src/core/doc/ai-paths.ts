import type { AuthoredAiPath, CoursePath, V3 } from './types';
import { aiLineRatings, aiPathLines, startGateLines, DEFAULT_AI_SEED } from './course';
import { aiPathEventSpan, aiPathMetrics } from '../reference/ai-paths';

export const AI_PATH_AUTHORING = { spacing: 9, sectionLength: 230, overlap: 20, maxError: 0.65 } as const;

/** Continuous generated routes for inspection; recorded sections always retain their leading indices. */
export function authoredAiDisplayPaths(
  course: CoursePath | null,
  seed: number,
  recorded: readonly AuthoredAiPath[] = [],
  automatic = true,
): AuthoredAiPath[] {
  return [
    ...recorded,
    ...(automatic && course && course.knots.length >= 2 ? authoredAiNetwork(course, seed).paths : []),
  ];
}

/** Shared rider/export network. Six start slots reference available routes; an empty network has none. */
export function authoredAiNetwork(
  course: CoursePath,
  seed = DEFAULT_AI_SEED,
  recorded: readonly AuthoredAiPath[] = [],
  wander = true,
  autoGenerated = true,
) {
  const saved = recorded.filter(path => path.points.length >= 2);
  if (!autoGenerated) {
    if (!saved.length) return { paths: [], starts: [] };
    const gates =
      course.knots.length >= 2 ? startGateLines(course).map(line => line[0]) : Array(6).fill(saved[0].points[0]);
    const starts = gates.map(gate =>
      saved.reduce(
        (best, path, index) =>
          horizontalDistance(path.points[0], gate) < horizontalDistance(saved[best].points[0], gate) ? index : best,
        0,
      ),
    );
    return { paths: [...saved], starts };
  }
  const ratings = aiLineRatings(course, seed, wander);
  const gates = aiPathLines(course, seed, wander).map((points, i) => ({
    id: `gate:${i}`,
    name: `AI Path ${i}`,
    rating: ratings[i],
    respawnable: true,
    points,
    events: [] as AuthoredAiPath['events'],
  }));
  if (!saved.length) return { paths: gates, starts: gates.map((_, i) => i) };
  // Recordings come first so an equally suitable recorded route wins a tie. Short fallback sections
  // provide coverage between recordings and let riders reselect into them throughout a mountain.
  const paths: AuthoredAiPath[] = [...saved];
  const starts: number[] = [];
  for (const gate of gates) {
    starts.push(paths.length);
    const total = aiPathMetrics(gate.points).length;
    paths.push({ ...gate, id: `${gate.id}:start`, points: aiPathEventSpan(gate.points, 0, Math.min(total, 25)) });
    for (let start = 0; start < total; start += AI_PATH_AUTHORING.sectionLength - AI_PATH_AUTHORING.overlap) {
      const points = aiPathEventSpan(gate.points, start, Math.min(total, start + AI_PATH_AUTHORING.sectionLength));
      if (points.length >= 2) paths.push({ ...gate, id: `${gate.id}:${start}`, points });
      if (start + AI_PATH_AUTHORING.sectionLength >= total) break;
    }
  }
  return { paths, starts };
}

/** Only finite, bounded document data reaches the controller/export; malformed paths are rejected on load. */
export function normalizeAiPaths(value: unknown): AuthoredAiPath[] | undefined {
  if (value === undefined) return undefined;
  if (!Array.isArray(value) || value.length > 4000) throw new Error('Invalid authored AI paths');
  const ids = new Set<string>();
  return value.map(path => {
    if (
      !path ||
      typeof path.id !== 'string' ||
      !path.id ||
      ids.has(path.id) ||
      typeof path.name !== 'string' ||
      !Number.isFinite(path.rating) ||
      path.rating < 0 ||
      path.rating > 100 ||
      typeof path.respawnable !== 'boolean' ||
      !Array.isArray(path.points) ||
      path.points.length < 2 ||
      path.points.length > 100000 ||
      !path.points.every(
        (p: unknown) => Array.isArray(p) && p.length === 3 && p.every(v => typeof v === 'number' && Number.isFinite(v)),
      ) ||
      !Array.isArray(path.events) ||
      path.events.length > 100000 ||
      !path.events.every(
        (e: AuthoredAiPath['events'][number]) =>
          e &&
          Number.isInteger(e.type) &&
          Number.isInteger(e.value) &&
          Number.isFinite(e.start) &&
          Number.isFinite(e.end) &&
          e.start >= 0 &&
          e.end >= e.start,
      )
    )
      throw new Error('Invalid authored AI path');
    ids.add(path.id);
    return structuredClone(path) as AuthoredAiPath;
  });
}

export function appendRecordedAiPaths(
  existing: readonly AuthoredAiPath[] | undefined,
  sections: readonly Omit<AuthoredAiPath, 'id' | 'name'>[],
): AuthoredAiPath[] {
  const paths = [...(existing ?? [])];
  for (const section of sections) {
    const id = Array.from(crypto.getRandomValues(new Uint32Array(4)), n => n.toString(16).padStart(8, '0')).join('');
    paths.push({ ...section, id: `ai:${id}`, name: `Recorded AI path ${paths.length + 1}` });
  }
  return paths;
}

export const horizontalDistance = (a: V3, b: V3) => Math.hypot(a[0] - b[0], a[2] - b[2]);

function pathStations(points: readonly V3[]): number[] {
  const result = [0];
  for (let i = 1; i < points.length; i++) result.push(result[i - 1] + horizontalDistance(points[i - 1], points[i]));
  return result;
}

function remapEvents(events: AuthoredAiPath['events'], before: number[], after: number[]): AuthoredAiPath['events'] {
  const station = (value: number) => {
    for (let i = 1; i < before.length; i++)
      if (value <= before[i])
        return (
          after[i - 1] +
          (after[i] - after[i - 1]) * Math.max(0, (value - before[i - 1]) / Math.max(1e-9, before[i] - before[i - 1]))
        );
    return after.at(-1)!;
  };
  return events.map(event => ({ ...event, start: station(event.start), end: station(event.end) }));
}

function nodeStation(path: AuthoredAiPath, node: number): number | null {
  if (!Number.isInteger(node) || !path.points[node]) return null;
  let station = 0;
  for (let i = 1; i <= node; i++) station += horizontalDistance(path.points[i - 1], path.points[i]);
  return station;
}

const pointReselectAt = (event: AuthoredAiPath['events'][number], station: number) =>
  event.type === 300 && Math.abs(event.start - station) < 1e-6 && Math.abs(event.end - station) < 1e-6;

/** Only point events placed at this node are toggled; existing reselection ranges remain independent. */
export function hasAiPathNodeReselect(path: AuthoredAiPath, node: number): boolean {
  const station = nodeStation(path, node);
  return station !== null && path.events.some(event => pointReselectAt(event, station));
}

export function setAiPathNodeReselect(path: AuthoredAiPath, node: number, enabled: boolean): AuthoredAiPath {
  const station = nodeStation(path, node);
  if (station === null || hasAiPathNodeReselect(path, node) === enabled) return path;
  return {
    ...path,
    events: enabled
      ? [...path.events, { type: 300, value: 0, start: station, end: station }]
      : path.events.filter(event => !pointReselectAt(event, station)),
  };
}

/** Keep event endpoints at the same fraction of their segment when editing a path's shape. */
export function moveAiPathNode(path: AuthoredAiPath, node: number, position: V3): AuthoredAiPath {
  if (!Number.isInteger(node) || !path.points[node] || !position.every(Number.isFinite)) return path;
  const points = path.points.map((p, i) => (i === node ? ([...position] as V3) : p));
  return {
    ...path,
    points,
    events: remapEvents(path.events, pathStations(path.points), pathStations(points)),
  };
}

/** Split the segment after `node` without changing the recorded line or event stations. */
export function insertAiPathNode(path: AuthoredAiPath, node: number): AuthoredAiPath {
  if (!Number.isInteger(node) || !path.points[node] || !path.points[node + 1] || path.points.length >= 100000)
    return path;
  const a = path.points[node],
    b = path.points[node + 1];
  const midpoint: V3 = [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2, (a[2] + b[2]) / 2];
  return { ...path, points: [...path.points.slice(0, node + 1), midpoint, ...path.points.slice(node + 1)] };
}

/** Preserve stations on surviving nodes, trim removed ends and remove the deleted node's reselect flag. */
export function deleteAiPathNode(path: AuthoredAiPath, node: number): AuthoredAiPath {
  if (!Number.isInteger(node) || !path.points[node] || path.points.length <= 2) return path;
  const points = path.points.filter((_, i) => i !== node);
  const stations = pathStations(path.points),
    before = stations.filter((_, i) => i !== node);
  const events = path.events.filter(
    event => !pointReselectAt(event, stations[node]) && event.end >= before[0] && event.start <= before.at(-1)!,
  );
  return { ...path, points, events: remapEvents(events, before, pathStations(points)) };
}
