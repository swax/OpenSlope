use slopesmith_multiplayer::protocol::*;
use std::{env, fs, path::Path};
use ts_rs::TS;

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap();
    let mut types = String::from("// Generated by multiplayer/export-protocol. Do not edit.\n");
    types.push_str(&format!(
        "export const PLAY_PROTOCOL_VERSION = {PROTOCOL_VERSION} as const;\n"
    ));
    types.push_str("export type PlayerVec3 = [number, number, number];\nexport type PlayerQuat = [number, number, number, number];\n");
    macro_rules! export { ($($ty:ty),+ $(,)?) => { $(types.push_str(&format!("export {}\n", <$ty>::decl(&ts_rs::Config::default())));)+ }; }
    export!(
        PlayerMode,
        PlayerGear,
        PlayerSnowboardStance,
        StockBoardId,
        PlayerEquipmentState,
        Hand,
        PointKind,
        MemberRole,
        RaceMode,
        RideEventKind,
        PlayerTransform,
        PlayerEquipmentPose,
        PlayerPointGesture,
        PlayerAnimation,
        PlayerPose,
        RideEventTarget,
        RideContact,
        RideEventMessage,
        PlayMember,
        MapSource,
        SiteCourse,
        SiteMember,
        TicketClaims,
        PlayConfig,
        TicketRequest,
        TicketResponse,
        PlayPeer,
        PeerPose,
        PlayChatLine,
        PlayClientMessage,
        PlayServerMessage,
        PlayControlMessage
    );
    let mut schemas = serde_json::Map::new();
    macro_rules! schema { ($($ty:ty),+ $(,)?) => { $(schemas.insert(stringify!($ty).into(), serde_json::to_value(schemars::schema_for!($ty)).unwrap());)+ }; }
    schema!(
        PlayClientMessage,
        PlayServerMessage,
        TicketClaims,
        TicketRequest,
        TicketResponse,
        PlayConfig,
        PlayControlMessage
    );
    // JSON Schema treats numeric formats as annotations. Encode Rust integer widths as actual constraints.
    fn numeric_bounds(value: &mut serde_json::Value) {
        match value {
            serde_json::Value::Object(object) => {
                let bounds = match object.get("format").and_then(|v| v.as_str()) {
                    Some("uint8") => Some((0, 255)),
                    Some("uint16") => Some((0, 65535)),
                    Some("uint32") => Some((0, 4294967295i64)),
                    Some("int8") => Some((-128, 127)),
                    _ => None,
                };
                if let Some((min, max)) = bounds {
                    object.insert("minimum".into(), min.into());
                    object.insert("maximum".into(), max.into());
                }
                for child in object.values_mut() {
                    numeric_bounds(child);
                }
            }
            serde_json::Value::Array(array) => {
                for child in array {
                    numeric_bounds(child);
                }
            }
            _ => {}
        }
    }
    for schema in schemas.values_mut() {
        numeric_bounds(schema);
    }
    let schema_text = format!("{}\n", serde_json::to_string_pretty(&schemas).unwrap());
    let outputs = [
        (
            root.join("src/core/session/play-protocol.generated.ts"),
            types,
        ),
        (root.join("multiplayer/protocol.schema.json"), schema_text),
    ];
    let check = env::args().any(|arg| arg == "--check");
    for (path, content) in outputs {
        if check {
            assert_eq!(
                fs::read_to_string(&path).unwrap_or_default(),
                content,
                "stale generated contract: {}",
                path.display()
            );
        } else {
            fs::write(path, content).unwrap();
        }
    }
}
